# -*- coding: utf-8 -*-
"""make_protected_terms.py - build pipeline/protected_terms.txt.

Sources:
  inventory/lib_stats.csv (library dir names, skip book:/tool:/root entries)
  docs/glossary_术语表.md section 5 first column (display names)
  manual tool/keyword list below
"""
from __future__ import annotations

import csv
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.stdout.reconfigure(encoding="utf-8", errors="replace")

from inventory import safe_join  # noqa: E402

WORKSPACE = Path(__file__).resolve().parent.parent

MANUAL = [
    "b2", "QuickBook", "BoostBook", "Doxygen", "AsciiDoc", "asciidoctor",
    "docca", "Antora", "boostdep", "bcp", "CMake", "Boost.Build",
    "Boost.Asio", "Boost.Python", "Boost.Test", "Boost.Graph",
    "Boost.Geometry", "Boost.Thread", "Boost.Filesystem", "Boost.JSON",
    "Boost.URL", "Boost.Regex", "Boost.Spirit", "Boost.Log",
    "Boost.Serialization", "Boost.Interprocess", "Boost.Multiprecision",
    "Boost.System", "Boost.Unordered", "Boost.Date_Time", "Boost.Stacktrace",
    "Boost.PropertyTree", "Boost.MPI", "Boost.Fiber", "Boost.Beast",
    "BOOST_RELEASE_VERSION", "BSL-1.0", "LICENSE_1_0.txt",
]


def main():
    terms = set(MANUAL)
    stats = safe_join(WORKSPACE, "inventory", "lib_stats.csv")
    with open(stats, newline="", encoding="utf-8-sig") as f:
        for r in csv.DictReader(f):
            lib = r["lib"]
            if lib.startswith(("tool:", "(book:", "(root)", "(antora")):
                continue
            if re.fullmatch(r"[A-Za-z0-9_]+", lib):
                terms.add(lib)

    gl = safe_join(WORKSPACE, "docs", "glossary_术语表.md")
    in_sec5 = False
    for line in gl.read_text(encoding="utf-8").splitlines():
        if line.startswith("## "):
            in_sec5 = "库名速查表" in line
            continue
        if in_sec5 and line.startswith("|") and not line.startswith("|--"):
            cols = [c.strip() for c in line.strip("|").split("|")]
            if cols and cols[0] and cols[0] != "库名（不译）":
                if re.fullmatch(r"[A-Za-z0-9_.]+", cols[0]):
                    terms.add(cols[0])

    out = safe_join(WORKSPACE, "pipeline", "protected_terms.txt")
    header = ("# protected terms: library names, display names, tool names\n"
              "# auto-generated by pipeline/make_protected_terms.py\n"
              "# baseline Boost 1.92.0, generated 2026-11-14\n")
    body = "\n".join(sorted(terms)) + "\n"
    out.write_text(header + body, encoding="utf-8")
    print(f"[terms] wrote {len(terms)} terms -> {out.name}")


if __name__ == "__main__":
    sys.exit(main())
